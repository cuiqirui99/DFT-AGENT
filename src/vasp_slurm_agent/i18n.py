LANGUAGE_NAMES = {"en": "English", "zh": "中文"}
_state = {"language": "en"}


def set_language(code: str) -> None:
    _state["language"] = code if code in LANGUAGE_NAMES else "en"


def current_language() -> str:
    return _state["language"]


def t(text: str) -> str:
    """Translate interface text; English is returned unchanged when no entry exists."""
    if _state["language"] == "en":
        return text
    table = TRANSLATIONS.get(_state["language"], {})
    return table.get(text, text)


